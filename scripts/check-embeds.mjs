// Which YouTube videos in the content refuse to play inside other sites (the uploader turned embedding off)?
// YouTube's oEmbed answers 401 for those and 404 for removed/private ones. The result goes to
// src/content/noembed.ts; the in-page player sends those straight to YouTube instead of showing an error.
// Run: node scripts/check-embeds.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dir = 'src/content';
const text = readdirSync(dir).filter(f => f.endsWith('.ts') && f !== 'noembed.ts').map(f => readFileSync(`${dir}/${f}`, 'utf8')).join('\n');
const ids = new Set();
for (const m of text.matchAll(/yt:\s*'([A-Za-z0-9_-]{11})'/g)) ids.add(m[1]);
for (const m of text.matchAll(/'([A-Za-z0-9_-]{11})',\s*\d+\s*\)/g)) ids.add(m[1]);

const blocked = [], gone = [];
for (const id of [...ids].sort()) {
  const r = await fetch(`https://www.youtube.com/oembed?format=json&url=${encodeURIComponent('https://www.youtube.com/watch?v=' + id)}`);
  if (r.status === 401 || r.status === 403) blocked.push(id);
  else if (r.status === 404 || r.status === 400) gone.push(id);
  console.log(id, r.status);
}
writeFileSync(`${dir}/noembed.ts`, `// Generated by scripts/check-embeds.mjs (${new Date().toISOString().slice(0, 10)}). Don't edit by hand.
/** Videos whose uploader turned off playing on other sites: open them on YouTube directly. */
export const NO_EMBED = new Set<string>(${JSON.stringify(blocked)});
/** Videos YouTube no longer finds (removed or private) at the last check. */
export const GONE = new Set<string>(${JSON.stringify(gone)});
`);
console.log(`\n${ids.size} videos: ${blocked.length} can't be embedded, ${gone.length} gone`);
